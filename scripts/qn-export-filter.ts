/**
 * Write the deployed Streams filter to quicknode/stream-filter.js (the exact source the stream runs),
 * for review and for the README. scripts/10-qn-stream.ts uploads the same source via the REST API.
 * Run: pnpm tsx scripts/qn-export-filter.ts
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { LIST_TREASURIES, LIST_WALLETS } from "../src/lib/quicknode/kv";
import { filterSource, STREAM_NAME } from "../src/lib/quicknode/streams";
import { TREASURY_FACTORY_ADDRESS } from "../src/lib/contracts/abis";

const src = `/* eslint-disable */ // generated; QuickNode calls main()
// Cosign: QuickNode Streams filter for stream "${STREAM_NAME}" (network arc-testnet, dataset logs).
// Generated by scripts/qn-export-filter.ts from src/lib/quicknode/filter.ts (buildKvFilterSource).
// Factory ${TREASURY_FACTORY_ADDRESS}; watched addresses live in the QuickNode Key-Value Store lists
// "${LIST_TREASURIES}" and "${LIST_WALLETS}", so adding a company or agent never redeploys the stream.
${filterSource()}
`;
mkdirSync("quicknode", { recursive: true });
writeFileSync("quicknode/stream-filter.js", src);
console.log(`wrote quicknode/stream-filter.js (${src.length} chars)`);
